function Get-DefaultRdpCanonicalDeployUnc {
    # UTF-8 bytes for 共有フォルダ\掲示板\rpa_luncher (WSL→powershell.exe で ps1 内日本語が化ける対策)
    $utf8 = [System.Text.Encoding]::UTF8
    $shareSuffix = $utf8.GetString([byte[]](
            0xE5, 0x85, 0xB1, 0xE6, 0x9C, 0x89,
            0xE3, 0x83, 0x95, 0xE3, 0x82, 0xA9, 0xE3, 0x83, 0xAB, 0xE3, 0x83, 0x80,
            0x5C,
            0xE6, 0x8E, 0xB2, 0xE7, 0xA4, 0xBA, 0xE6, 0x9D, 0xBF,
            0x5C,
            0x72, 0x70, 0x61, 0x5F, 0x6C, 0x75, 0x6E, 0x63, 0x68, 0x65, 0x72))
    return '\\192.168.0.101\' + $shareSuffix
}

function Resolve-RdpCanonicalDeployDir {
    param([string]$Override)
    if (-not [string]::IsNullOrWhiteSpace($Override)) {
        return $Override.Trim().TrimEnd('\', '/')
    }
    $fromEnv = $env:PM_AI_RDP_CANONICAL_DEPLOY_DIR
    if (-not [string]::IsNullOrWhiteSpace($fromEnv)) {
        return $fromEnv.Trim().TrimEnd('\', '/')
    }
    return Get-DefaultRdpCanonicalDeployUnc
}

function Build-RdpLauncherPortableBatContent {
    param(
        [string]$JavafxVersion,
        [string]$JvmInitial,
        [string]$JvmMax,
        [string]$LauncherExeBaseName = 'PmAiRpaLuncher'
    )
    $jv = ($JavafxVersion -replace '[\r\n\t]', '').Trim()
    if ([string]::IsNullOrWhiteSpace($jv)) {
        $jv = '26.0.1'
    }
    $xms = Normalize-JvmHeapToken $JvmInitial
    $xmx = Normalize-JvmHeapToken $JvmMax
    $lines = [System.Collections.Generic.List[string]]::new()
    $lines.Add('@echo off')
    $lines.Add('rem ASCII-only. Generated by package_rdp_launcher_app.ps1')
    $lines.Add('rem Do not paste into PowerShell; run: .\launch-pm-ai-rdp-launcher.bat')
    $lines.Add('setlocal EnableExtensions EnableDelayedExpansion')
    $lines.Add('')
    $lines.Add('set "ROOT=%~dp0"')
    $lines.Add('if "%ROOT:~-1%"=="\" set "ROOT=%ROOT:~0,-1%"')
    $lines.Add('cd /d "%ROOT%"')
    $lines.Add('')
    $lines.Add('if not exist "%ROOT%\app" (')
    $lines.Add('    echo [ERROR] Missing app folder. Put this bat next to ' + $LauncherExeBaseName + '.exe / app / runtime.')
    $lines.Add('    echo Current: "%ROOT%"')
    $lines.Add('pause')
    $lines.Add('    exit /b 1')
    $lines.Add(')')
    $lines.Add('')
    $lines.Add('set "JAVA_EXE=%ROOT%\runtime\bin\java.exe"')
    $lines.Add('if exist "%JAVA_EXE%" goto :have_java')
    $lines.Add('if defined JAVA_HOME (')
    $lines.Add('    if exist "%JAVA_HOME%\bin\java.exe" (')
    $lines.Add('        set "JAVA_EXE=%JAVA_HOME%\bin\java.exe"')
    $lines.Add('        echo [WARN] Using JAVA_HOME java.exe (bundled runtime missing).')
    $lines.Add('        goto :have_java')
    $lines.Add('    )')
    $lines.Add(')')
    $lines.Add('echo [ERROR] Java not found: "%ROOT%\runtime\bin\java.exe"')
    $lines.Add('pause')
    $lines.Add('exit /b 1')
    $lines.Add('')
    $lines.Add(':have_java')
    $lines.Add('set "PM_AI_JFX_MODPATH=%ROOT%\app\jfx-mod"')
    $compatJvm = '--add-opens=javafx.base/com.sun.javafx.event=ALL-UNNAMED --add-opens=javafx.controls/javafx.scene.control.skin=ALL-UNNAMED --add-opens=javafx.controls/com.sun.javafx.scene.control.behavior=ALL-UNNAMED --add-exports=javafx.controls/com.sun.javafx.scene.control.behavior=ALL-UNNAMED --enable-native-access=javafx.graphics'
    $javaLine = '"%JAVA_EXE%" -Dfile.encoding=UTF-8 -Xms' + $xms + ' -Xmx' + $xmx + ' -Dprism.order=sw ' + $compatJvm + ' --module-path "!PM_AI_JFX_MODPATH!" --add-modules javafx.controls,javafx.fxml,javafx.graphics,javafx.base,javafx.media,javafx.swing -classpath "%ROOT%\app\*" jp.co.pm.ai.desktop.RemoteDesktopFxApp %*'
    $lines.Add($javaLine)
    $lines.Add('set EXITCODE=!ERRORLEVEL!')
    $lines.Add('if !EXITCODE! neq 0 (')
    $lines.Add('    echo.')
    $lines.Add('    echo [Exit !EXITCODE!] Logs: !USERPROFILE!\.pm-ai-desktop-rdp\')
    $lines.Add(')')
    $lines.Add('exit /b !EXITCODE!')
    $lines.Add('')
    return ($lines.ToArray() -join "`r`n")
}

function Copy-RdpLauncherDeploySeed {
    param(
        [string]$DistAppRoot,
        [string]$ClassesRdpLauncherDir,
        [string]$ResourcesRdpLauncherDir
    )
    $seed = Join-Path $DistAppRoot 'launcher-deploy-seed'
    if (Test-Path -LiteralPath $seed) {
        Remove-Item -Recurse -Force $seed
    }
    New-Item -ItemType Directory -Path $seed -Force | Out-Null
    $sourceDir = $ClassesRdpLauncherDir
    if (-not (Test-Path -LiteralPath $sourceDir)) {
        $sourceDir = $ResourcesRdpLauncherDir
    }
    if (-not (Test-Path -LiteralPath $sourceDir)) {
        Write-Warning "RDP C# launcher resources missing (build with dotnet or run without -SkipCsLauncherBuild)"
        return
    }
    Copy-Item -Path (Join-Path $sourceDir '*') -Destination $seed -Force
    $exeInSeed = Join-Path $seed 'PmAiRdpRemoteLauncher.exe'
    if (-not (Test-Path -LiteralPath $exeInSeed)) {
        Write-Warning "launcher-deploy-seed has no PmAiRdpRemoteLauncher.exe — run scripts/build-rdp-remote-launcher.ps1"
    }
    Write-Host "launcher-deploy-seed: $seed" -ForegroundColor DarkGray
}

<#
  jpackage native exe fails to expand $APPDIR on Unicode install paths (Japanese folder names).
  Replace with C# stub that resolves exe directory and spawns runtime\bin\java.exe (same as .bat).
#>
function Install-RdpDesktopLauncherExe {
    param(
        [Parameter(Mandatory)][string]$BundleRoot,
        [Parameter(Mandatory)][string]$AppExeBaseName,
        [Parameter(Mandatory)][string]$WorkspaceRootPath
    )
    $targetExe = Join-Path $BundleRoot ($AppExeBaseName + '.exe')
    $stubExe = Join-Path $BundleRoot ($AppExeBaseName + '-jpackage-stub.exe')
    $resourceExe = Join-Path $WorkspaceRootPath 'code_java/src/main/resources/jp/co/pm/ai/desktop/rdp-launcher/PmAiRpaLuncher.exe'
    $publishExe = Join-Path $WorkspaceRootPath 'tools/pm-ai-rdp-desktop-launcher/bin/Release/net8.0-windows/win-x64/publish/PmAiRdpDesktopLauncher.exe'
    $srcExe = $null
    if (Test-Path -LiteralPath $resourceExe) {
        $srcExe = $resourceExe
    }
    elseif (Test-Path -LiteralPath $publishExe) {
        $srcExe = $publishExe
    }
    if (-not $srcExe) {
        throw @"
Desktop launcher stub missing. Build with:
  scripts/build-rdp-desktop-launcher.ps1
or run package without -SkipCsLauncherBuild.
Expected: $resourceExe
"@
    }
    if (Test-Path -LiteralPath $targetExe) {
        if (Test-Path -LiteralPath $stubExe) {
            Remove-Item -LiteralPath $stubExe -Force -ErrorAction SilentlyContinue
        }
        Move-Item -LiteralPath $targetExe -Destination $stubExe -Force
        Write-Host "Renamed jpackage stub: $stubExe" -ForegroundColor DarkGray
    }
    Copy-Item -LiteralPath $srcExe -Destination $targetExe -Force
    Write-Host "Installed Unicode-safe desktop launcher: $targetExe" -ForegroundColor DarkGray
}

function Test-RdpPortableLauncherExe {
    param(
        [Parameter(Mandatory)][string]$BundleRoot,
        [Parameter(Mandatory)][string]$AppExeBaseName
    )
    $mainExe = Join-Path $BundleRoot ($AppExeBaseName + '.exe')
    if (-not (Test-Path -LiteralPath $mainExe)) {
        throw "Portable launcher exe missing: $mainExe (jpackage app-image should create it next to app\ and runtime\)."
    }
    $diagBin = Join-Path $BundleRoot 'runtime\bin'
    $bundledJavaExe = Join-Path $diagBin 'java.exe'
    $exeInBin = @()
    if (Test-Path -LiteralPath $diagBin) {
        $exeInBin = @(Get-ChildItem -LiteralPath $diagBin -Filter '*.exe' -File -ErrorAction SilentlyContinue)
    }
    $hasJavaExe = Test-Path -LiteralPath $bundledJavaExe
    if (-not $hasJavaExe -and $exeInBin.Count -gt 0) {
        $hasJavaExe = [bool]($exeInBin | Where-Object { $_.Name -ieq 'java.exe' })
    }
    if (-not $hasJavaExe) {
        Write-Warning @"
Bundled JVM launcher missing: $bundledJavaExe
Common causes: Windows Defender removed java.exe; non-ASCII repo path (use -JpackageDest); stale dist.
Portable start uses $AppExeBaseName.exe — fix runtime before distributing.
"@
    }
    return $mainExe
}

function Publish-RdpPortableBundleToRelease {
    param(
        [Parameter(Mandatory)][string]$DistAppRoot,
        [Parameter(Mandatory)][string]$ReleaseRootPath,
        [Parameter(Mandatory)][string]$AppFolderName
    )
    New-Item -ItemType Directory -Path $ReleaseRootPath -Force | Out-Null
    $releaseBundle = Join-Path $ReleaseRootPath $AppFolderName
    $publishTarget = $releaseBundle
    if (Test-Path -LiteralPath $releaseBundle) {
        $removed = Remove-DirectoryWithRetry -Path $releaseBundle -CloseHint 'close PmAiRpaLuncher.exe / Explorer on release folder'
        if (-not $removed) {
            Write-Host "--- Release folder locked; mirror with robocopy: $releaseBundle ---" -ForegroundColor Cyan
            $roboExit = Mirror-DirectoryWithRobocopy -Source $DistAppRoot -Destination $releaseBundle
            if ($roboExit -lt 8) {
                Write-Host "Release folder updated (robocopy): $releaseBundle" -ForegroundColor Green
                return (Resolve-Path -LiteralPath $releaseBundle).Path
            }
            $publishTarget = Join-Path $ReleaseRootPath ($AppFolderName + '-build-' + [Guid]::NewGuid().ToString('N').Substring(0, 12))
            Write-Warning "Release folder still locked; publishing alternate bundle: $publishTarget"
        }
    }
    if ($publishTarget -ne $releaseBundle -or -not (Test-Path -LiteralPath $releaseBundle)) {
        Copy-Item -Recurse -Force -LiteralPath $DistAppRoot -Destination $publishTarget
    }
    return (Resolve-Path -LiteralPath $publishTarget).Path
}

function Read-AppVersionFromRepo {
    param(
        [string]$WorkspaceRootPath,
        [string]$FallbackVersion
    )
    $versionTxt = Join-Path $WorkspaceRootPath 'version.txt'
    $appVer = $FallbackVersion -replace '-SNAPSHOT$', '.0'
    if (Test-Path -LiteralPath $versionTxt) {
        $rawTxt = (Get-Content -LiteralPath $versionTxt -TotalCount 1 -Encoding UTF8).Trim()
        if (-not [string]::IsNullOrWhiteSpace($rawTxt)) {
            $digits = -join ($rawTxt.ToCharArray() | Where-Object { [char]::IsDigit($_) -or $_ -eq '.' })
            if (-not [string]::IsNullOrWhiteSpace($digits)) {
                $appVer = $digits
                if ($appVer -match '^\d+\.\d+$') {
                    $appVer = "$appVer.0"
                }
            }
        }
    }
    return $appVer
}

