    'Shared DATA (default): \\\\192.168.0.101\\共有フォルダ\\掲示板\\rpa_luncher\\DATA',
    '  RAP設定.ini, operator users bin — see User Administrator tab.',
    'Launcher deploy folder (remote exe): PM_AI_RDP_LAUNCHER_DEPLOY_DIR = rpa_luncher (not DATA).',
    'Auto-update canonical (default PM_AI_RDP_PORTABLE_BUNDLE_SOURCE_DIR):',
    "  $canonicalDeployUncForDocs",
    '  (version.txt + PmAiRpaLuncher_version_upgrade.zip + build-manifest.json)',
    ''
) | Set-Content -LiteralPath $readme -Encoding UTF8

$batDst = Join-Path $distRoot 'launch-pm-ai-rpa-luncher.bat'
$batBody = Build-RdpLauncherPortableBatContent -JavafxVersion $javafxVer -JvmInitial $jvmInitial -JvmMax $jvmMax -LauncherExeBaseName $APP_NAME
[System.IO.File]::WriteAllText($batDst, $batBody, [System.Text.UTF8Encoding]::new($false))

$applyScriptSrc = Join-Path $WorkspaceRoot 'scripts/rdp-apply-portable-update.ps1'
if (Test-Path -LiteralPath $applyScriptSrc) {
    Copy-Item -LiteralPath $applyScriptSrc -Destination (Join-Path $distRoot 'rdp-apply-portable-update.ps1') -Force
    Write-Host "Portable update script: rdp-apply-portable-update.ps1" -ForegroundColor DarkGray
}

$mainExePath = Test-RdpPortableLauncherExe -BundleRoot $distRoot -AppExeBaseName $APP_NAME
Write-Host "Portable launcher exe verified: $mainExePath" -ForegroundColor DarkGray

$releaseBundlePath = Publish-RdpPortableBundleToRelease -DistAppRoot $distRoot -ReleaseRootPath $ReleaseRoot -AppFolderName $APP_NAME
$releaseExePath = Join-Path $releaseBundlePath ($APP_NAME + '.exe')
Write-Host "--- Published runnable portable bundle: $releaseBundlePath ---" -ForegroundColor Cyan
Write-Host "Start from exe: $releaseExePath" -ForegroundColor Green

Write-Host "--- Done ---" -ForegroundColor Green
Write-Host "Portable app: $mainExePath"
Write-Host "Release exe:  $releaseExePath"
Write-Host "Deploy seed:  $(Join-Path $distRoot 'launcher-deploy-seed')"

$upgradeZipName = 'PmAiRpaLuncher_version_upgrade.zip'
$upgradeZipPath = Join-Path $ReleaseRoot $upgradeZipName

if (-not $SkipZip) {
    New-Item -ItemType Directory -Path $ReleaseRoot -Force | Out-Null
    $zipPortable = Join-Path $ReleaseRoot 'PmAiRpaLuncher_portable.zip'
    if (Test-Path -LiteralPath $zipPortable) {
        Remove-Item -Force -LiteralPath $zipPortable
    }
    Write-Host "--- ZIP portable: $zipPortable ---" -ForegroundColor Cyan
    Compress-Archive -LiteralPath $distRoot -DestinationPath $zipPortable -CompressionLevel Fastest -Force
    Write-Host "Portable ZIP: $zipPortable" -ForegroundColor Green

    if (Test-Path -LiteralPath $upgradeZipPath) {
        Remove-Item -Force -LiteralPath $upgradeZipPath
    }
    Write-Host "--- ZIP version upgrade: $upgradeZipPath ---" -ForegroundColor Cyan
    Compress-Archive -LiteralPath $distRoot -DestinationPath $upgradeZipPath -CompressionLevel Fastest -Force
    Write-Host "Version upgrade ZIP: $upgradeZipPath" -ForegroundColor Green

    $releaseVersionTxt = Join-Path $ReleaseRoot 'version.txt'
    Copy-Item -LiteralPath (Join-Path $WorkspaceRoot 'version.txt') -Destination $releaseVersionTxt -Force -ErrorAction SilentlyContinue

    $desktopJar = Get-ChildItem -LiteralPath (Join-Path $distRoot 'app') -Filter 'production-control-desktop*.jar' -File -ErrorAction SilentlyContinue |
        Select-Object -First 1
    if ($desktopJar) {
        $sha = (Get-FileHash -LiteralPath $desktopJar.FullName -Algorithm SHA256).Hash
        $verLine = if (Test-Path -LiteralPath $releaseVersionTxt) {
            (Get-Content -LiteralPath $releaseVersionTxt -TotalCount 1 -Encoding UTF8).Trim()
        } else { $APP_VERSION }
        $manifestObj = [ordered]@{
            version            = $verLine
            desktopJarFileName = $desktopJar.Name
            desktopJarSize     = $desktopJar.Length
            desktopJarSha256   = $sha
        }
        $manifestPath = Join-Path $ReleaseRoot 'build-manifest.json'
        $manifestObj | ConvertTo-Json | Set-Content -LiteralPath $manifestPath -Encoding utf8
        Write-Host "build-manifest.json: $manifestPath" -ForegroundColor DarkGray
    }

    if (-not $SkipCanonicalDeploy) {
        $canon = Resolve-RdpCanonicalDeployDir -Override $CanonicalDeployDir
        if ([string]::IsNullOrWhiteSpace($canon)) {
            Write-Warning 'CanonicalDeployDir is empty; skip deploy to network canonical folder.'
        }
        else {
            Write-Host "--- Deploy release artifacts to canonical UNC: $canon ---" -ForegroundColor Cyan
            try {
                New-Item -ItemType Directory -Path $canon -Force -ErrorAction Stop | Out-Null
                foreach ($artifact in @(
                        $zipPortable,
                        $upgradeZipPath,
                        $releaseVersionTxt,
                        (Join-Path $ReleaseRoot 'build-manifest.json'))) {
                    if (Test-Path -LiteralPath $artifact) {
                        Copy-Item -LiteralPath $artifact -Destination (Join-Path $canon (Split-Path -Leaf $artifact)) -Force -ErrorAction Stop
                        Write-Host "  -> $(Split-Path -Leaf $artifact)" -ForegroundColor DarkGray
                    }
                }
                Write-Host "Canonical deploy done: $canon" -ForegroundColor Green
            }
            catch {
                Write-Warning "Canonical deploy failed: $($_.Exception.Message)"
                Write-Warning "Local release is ready under $ReleaseRoot. Offline/WSL: use -SkipCanonicalDeploy or copy manually to the share."
            }
        }
    }
}
